def render_ssi_pins(pins: dict[str, dict], parts_map: dict, pinmux: dict) -> str:
    out = [f"pin!({cfg}{inst}, {kind}, {name}, {f['reg']}, {f['shift']}, {f['width']}, {fn});"
           for _, kind, _, name, cfg, inst, f, fn in _driver_rows(pins, parts_map, pinmux, SSI_SIGNALS, "SSI")]
    out += [f"clkin!({cfg}{name}, {f['reg']}, {f['shift']}, {f['width']}, {fn});"
            for _, _, _, name, cfg, _, f, fn in _driver_rows(pins, parts_map, pinmux, SSI_CLKIN, "SSI")]
    return SSI_PINS_HEADER + "\n".join(out) + "\n"


def render_esdhc_pins(pins: dict[str, dict], parts_map: dict, pinmux: dict) -> str:
    rows = _driver_rows(pins, parts_map, pinmux, ESDHC_SIGNALS, "ESDHC")
    return ESDHC_PINS_HEADER + "\n".join(
        f"pin!({cfg}{kind}, {name}, {f['reg']}, {f['shift']}, {f['width']}, {fn});"
        for _, kind, _, name, cfg, _, f, fn in rows) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("pins")
    ap.add_argument("parts_map")
    ap.add_argument("pinmux")
    ap.add_argument("-o", required=True)
    ap.add_argument("--uart-pins", required=True)
    ap.add_argument("--spi-pins", required=True)
    ap.add_argument("--esdhc-pins", required=True)
    ap.add_argument("--ssi-pins", required=True)
    a = ap.parse_args()
    pins, parts_map, pinmux = (json.loads(Path(x).read_text()) for x in (a.pins, a.parts_map, a.pinmux))
    Path(a.o).write_text(render(pins, parts_map, pinmux))
    Path(a.uart_pins).write_text(render_uart_pins(pins, parts_map, pinmux))
    Path(a.spi_pins).write_text(render_spi_pins(pins, parts_map, pinmux))
    Path(a.esdhc_pins).write_text(render_esdhc_pins(pins, parts_map, pinmux))
    Path(a.ssi_pins).write_text(render_ssi_pins(pins, parts_map, pinmux))


if __name__ == "__main__":
    main()
