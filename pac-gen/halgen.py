"""embassy-mcf5441x/src/peripherals.rs, src/uart/pins.rs, src/spi/pins.rs, src/esdhc/pins.rs and src/ssi/pins.rs: the
HAL's peripheral tokens, gated per part (parts_map.json's absent lists; pins by package from pins.json), with their PAC
register blocks, pin coordinates and PAR fields (pinmux.json), and the UART, DSPI, eSDHC and SSI pin impls drawn from
the pins' Table 15-2 functions.
Usage: halgen.py <pins.json> <parts_map.json> <pinmux.json> -o <peripherals.rs> --uart-pins <uart/pins.rs>
       --spi-pins <spi/pins.rs> --esdhc-pins <esdhc/pins.rs> --ssi-pins <ssi/pins.rs>"""
import argparse
import json
import re
from pathlib import Path

PARTS = ["mcf54410", "mcf54415", "mcf54416", "mcf54417", "mcf54418"]
PACKAGE = {"mcf54410": "196", "mcf54415": "256", "mcf54416": "256", "mcf54417": "256", "mcf54418": "256"}
# token → PAC register block (module::Type); DMA channels share EDMA and have none
BLOCKS = {**{f"PIT{i}": "pit0::Pit0" for i in range(4)}, **{f"UART{i}": "uart0::Uart0" for i in range(10)},
          **{f"DSPI{i}": "dspi0::Dspi0" for i in range(4)}, **{f"I2C{i}": "i2c0::I2c0" for i in range(6)},
          **{f"SSI{i}": "ssi0::Ssi0" for i in range(2)}, "ESDHC": "esdhc::Esdhc", "USBOTG": "usbotg::Usbotg"}


def _parts(present: list[str], token: str) -> str | None:
    if not present:
        raise SystemExit(f"halgen: {token} is present on no part (an empty cfg would leave it on every part)")
    if present == PARTS:
        return None
    return (f'feature = "{present[0]}"' if len(present) == 1
         else "any(" + ", ".join(f'feature = "{p}"' for p in present) + ")")


def _cfg(*conds: str | None) -> str:
    c = list(dict.fromkeys(x for x in conds if x))      # drop empties and repeats, keep order
    if not c:
        return ""
    return f"#[cfg({c[0] if len(c) == 1 else 'all(' + ', '.join(c) + ')'})] "


PORTS = "ABCDEFGHIJK"


def _par(pinmux: dict, gpio: bool) -> dict[str, dict]:
    """Pin → its settled PAR field. For GPIO, reserved fields (a pad carrying a boot function) are left out too;
    drivers may select them. Unverified fields and group pads have none."""
    return {f["pin"]: f for f in pinmux["fields"] if f["verified"] and not (gpio and f.get("reserved"))}


def _mux(field: dict | None) -> str:
    if field is None:
        return "None"
    return f"Some(crate::pinmux::ParField::new(crate::pinmux::{field['reg']}, {field['shift']}, {field['width']}))"


def render(pins: dict[str, dict], parts_map: dict, pinmux: dict) -> str:
    absent = parts_map["absent"]
    par = _par(pinmux, gpio=True)
    rows = []                                   # (token, cfg prefix, impl line or None)
    for t, block in BLOCKS.items():
        pit = f'not(feature = "time-driver-pit{t[3]}")' if t.startswith("PIT") else None
        cfg = _cfg(_parts([p for p in PARTS if t not in absent[p]], t), pit)
        rows.append((t, cfg, f"impl_regs!({t}, {block});"))
    rows += [(f"DMA_CH{i}", "", f"impl_dma_channel!(DMA_CH{i}, {i}, "
              f"{'EDMA_INTR_INT56_63' if i >= 56 else f'EDMA_INTR_INT{i:02d}'});") for i in range(64)]
    for name, info in pins.items():
        cfg = _cfg(_parts([p for p in PARTS if PACKAGE[p] in info["packages"]], name))
        rows.append((name, cfg, f"impl_pin!({name}, {PORTS.index(name[1])}, {name[2]}, {_mux(par.get(name))});"))
    out = ["// @generated by pac-gen/halgen.py from pins.json, pinmux.json and pac-gen/parts_map.json: do not edit.",
           "embassy_hal_internal::peripherals! {"]
    out += [f"    {cfg}{t}," for t, cfg, _ in rows]
    out.append("}")
    out += [f"{cfg}{line}" for _, cfg, line in rows if line]
    return "\n".join(out) + "\n"

# Driver signals: (pattern over Table 15-2 names, pin trait). The boot-flash pads are written with their serial-boot
# alias ("DSPI0_SCK/SBF_CK"), so DSPI names may continue after "/". 3d–3e add eSDHC and USB here.
UART_SIGNALS = [(re.compile(r"^UART(\d)_TXD$"), "TxPin"), (re.compile(r"^UART(\d)_RXD$"), "RxPin")]
SPI_SIGNALS = [(re.compile(r"^DSPI(\d)_SCK(?:/|$)"), "SckPin"), (re.compile(r"^DSPI(\d)_SOUT(?:/|$)"), "SoutPin"),
               (re.compile(r"^DSPI(\d)_SIN(?:/|$)"), "SinPin"), (re.compile(r"^DSPI(\d)_PCS(\d)(?:/|$)"), "PcsPin")]
# The one eSDHC has no instance digit; DAT4-7 are left out (the controller's data bus is at most 4 bits here).
ESDHC_SIGNALS = [(re.compile(r"^SDHC_CLK(?:/|$)"), "ClkPin"), (re.compile(r"^SDHC_CMD(?:/|$)"), "CmdPin")] + [
    (re.compile(rf"^SDHC_DAT{n}(?:/|$)"), f"Dat{n}Pin") for n in range(4)]
# Each SSI's bit clock, frame sync, data and master clock; SSI_CLKIN (the external audio clock input) has no instance.
SSI_SIGNALS = [(re.compile(rf"^SSI(\d)_{s}$"), k) for s, k in
               (("BCLK", "BclkPin"), ("FS", "FsPin"), ("TXD", "TxdPin"), ("RXD", "RxdPin"), ("MCLK", "MclkPin"))]
SSI_CLKIN = [(re.compile(r"^SSI_CLKIN$"), "ClkinPin")]
COLUMN_FUNCTION = {"primary": "Primary", "alt1": "Alt1", "alt2": "Alt2"}

UART_PINS_HEADER = '''// @generated by pac-gen/halgen.py from pins.json, pinmux.json and pac-gen/parts_map.json: do not edit.
//! The pads each UART's TXD and RXD can use, and the PAR field and function that select them (RM Table 15-2;
//! pac-gen/tests/test_uart_pins.py checks every row against it).
use crate::pinmux::{Function, ParField};

macro_rules! pin {
    ($(#[$m:meta])* $uart:ident, $kind:ident, $pin:ident, $reg:ident, $shift:expr, $width:expr, $f:ident) => {
        $(#[$m])*
        impl super::sealed::$kind<crate::peripherals::$uart> for crate::peripherals::$pin {
            const PAR: ParField = ParField::new(crate::pinmux::$reg, $shift, $width);
            const FUNCTION: Function = Function::$f;
        }
        $(#[$m])*
        impl super::$kind<crate::peripherals::$uart> for crate::peripherals::$pin {}
    };
}

'''

